--7.How many customer have >10 transaction with us, excluding returns

SELECT  C.customer_Id, COUNT(customer_Id) AS No_of_cust
FROM customer AS C
LEFT JOIN transactions AS T
ON C.customer_Id = T.cust_id
WHERE T.Qty > 0
GROUP BY customer_Id
HAVING COUNT(customer_Id) > 10

--8.What is the combine revenue from the "Electronics" and "Clothing" category, from "Flagship store"?

SELECT prod_cat, ROUND(SUM(t.total_amt),0) AS total_amount
FROM [product category information] AS P
JOIN transactions AS T
ON P.prod_sub_cat_code = T.prod_subcat_code
WHERE P.prod_cat IN ('Electronics', 'Clothing')
	AND T.Store_type = 'Flagship store'
